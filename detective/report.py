"""Final case report (Markdown), with every citation checked against the source documents.

Citations appear in two forms:
  quoted:    “2026-03-12 19:41 | Marcus Hale | Main Entrance | ENTRY” [badge_log:L6]
             the quoted text must appear on that line of that document;
  reference: [badge_log:L6]
             the document must exist and have that line.
`check_citations` parses the finished report text (not the objects used to build it), so it
also catches mistakes in the report code itself. `build_report` refuses to return a report with
a citation that fails the check.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

from .alibi import Verdict
from .investigator import Label, Step
from .models import Case, EvidenceKind, Quote

_QUOTED = re.compile(r"“([^”]+)”\s*\[([A-Za-z0-9_]+):L(\d+)\]")
_REF = re.compile(r"\[([A-Za-z0-9_]+):L(\d+)\]")


@dataclass
class CitationCheck:
    quoted: int = 0
    references: int = 0
    problems: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.problems


class ReportCitationError(AssertionError):
    pass


def check_citations(case: Case, text: str) -> CitationCheck:
    result = CitationCheck()
    lines = {d.id: d.body.splitlines() for d in case.documents.values()}
    quoted_spans = []
    for m in _QUOTED.finditer(text):
        result.quoted += 1
        quoted_spans.append(m.span())
        quote, doc, n = m.group(1), m.group(2), int(m.group(3))
        if doc not in lines:
            result.problems.append(f"[{doc}:L{n}] cites a document that is not in the case")
        elif not 1 <= n <= len(lines[doc]):
            result.problems.append(f"[{doc}:L{n}] cites a line that does not exist")
        elif quote not in lines[doc][n - 1]:
            result.problems.append(f"[{doc}:L{n}] does not contain “{quote}”")
    for m in _REF.finditer(text):
        if any(a <= m.start() < b for a, b in quoted_spans):
            continue
        result.references += 1
        doc, n = m.group(1), int(m.group(2))
        if doc not in lines or not 1 <= n <= len(lines[doc]):
            result.problems.append(f"[{doc}:L{n}] points to a document or line that does not exist")
    return result


def _cite(q: Quote) -> str:
    return f"“{q.text}” [{q.cite()}]"


def _step_lines(step: Step, indent: str = "") -> list[str]:
    out = [f"{indent}- **{step.weight:+.1f} {step.label.value.upper()}** ({step.kind}"
           f"{', from LLM' if step.source == 'llm' else ''}): {step.text}"]
    if step.tested:
        out.append(f"{indent}  - statement checked: {_cite(step.tested)}")
    for q in step.evidence:
        if q != step.tested:
            out.append(f"{indent}  - {_cite(q)}")
    return out


def build_report(inv, earlier=None) -> str:
    """Markdown report for an Investigation. `earlier` is the same case at an earlier evidence stage."""
    case: Case = inv.index.case
    a = inv.assessment
    ranked = a.ranking()
    top = ranked[0]
    level, reasons = a.confidence_reasons()
    out: list[str] = []
    stage = max((d.stage for d in case.documents.values()), default=1)

    out += [f"# Case report: {case.title}", "",
            f"*Case `{case.id}` · difficulty: {case.difficulty} · {len(case.documents)} documents "
            f"(evidence up to stage {stage}) · generated by AI Detective*", "",
            case.summary, ""]

    out += ["## Conclusion", "",
            f"**Most likely suspect: {top.suspect}** (score {top.score:+.1f}). "
            f"**Confidence: {level}.**", ""]
    out += [f"- {r}" for r in reasons]
    key = sorted((s for s in top.steps if s.weight > 0), key=lambda s: -s.weight)[:3]
    if key:
        out += ["", "Strongest points:"]
        out += [f"{i}. {s.text}" for i, s in enumerate(key, 1)]
    out.append("")

    out += ["## Ranking", "",
            "| Suspect | Score | Facts | Statements | Assumptions | Speculation (always 0) |",
            "|---|---|---|---|---|---|"]
    for log in ranked:
        def total(label: Label) -> str:
            return f"{sum(s.weight for s in log.steps if s.label is label):+.1f}"
        spec = sum(1 for s in log.steps if s.label is Label.SPECULATION)
        out.append(f"| {log.suspect} | **{log.score:+.1f}** | {total(Label.FACT)} | {total(Label.CLAIM)} | "
                   f"{total(Label.ASSUMPTION)} | {spec} flagged |")
    out += ["", "Labels: **FACT** = decided by records (badge log, login log, CCTV, brief); "
            "**CLAIM** = rests on what someone said or wrote; **ASSUMPTION** = an inference; "
            "**SPECULATION** = a guess, shown but never counted.", ""]

    out += [f"## The case against {top.suspect}", ""]
    for s in sorted(top.steps, key=lambda s: -s.weight):
        if s.weight != 0:
            out += _step_lines(s)
    zero = [s for s in top.steps if s.weight == 0]
    if zero:
        out += ["", "Also noted (no weight):"]
        for s in zero:
            out += _step_lines(s)
    out.append("")

    out += ["## Why not the others", ""]
    for log in ranked[1:]:
        out += [f"### {log.suspect} ({log.score:+.1f})", ""]
        for s in sorted(log.steps, key=lambda s: s.weight):
            out += _step_lines(s)
        out.append("")

    out += ["## Contradictions", ""]
    found = False
    for name, alibi in inv.alibis.items():
        for c in alibi.checks:
            if c.verdict is Verdict.CONTRADICTED:
                found = True
                speaker = c.claim.reported_by or name
                out.append(f"- **{speaker}**'s statement about {name if c.claim.reported_by else 'themselves'} "
                           f"is contradicted by records: {_cite(c.claim.quote)}")
                out += [f"  - record: {_cite(q)}" for q in c.evidence]
    for conflict in inv.conflicts:
        found = True
        out.append(f"- **Statements conflict** about {conflict.person}: {conflict.explanation()}")
        out += [f"  - {_cite(conflict.a.claim.quote)}", f"  - {_cite(conflict.b.claim.quote)}"]
    for c in inv.connections:
        if c.denial:
            found = True
            out.append(f"- **{c.suspect} denied contact** with {c.party}: {_cite(c.denial)}")
            out += [f"  - message: {_cite(q)}" for q in c.messages]
    if not found:
        out.append("- None found.")
    out.append("")

    out += ["## Misleading evidence set aside", ""]
    for d in inv.disputes:
        out.append(f"- **Disputed record** (left out of alibi and opportunity checks): {d.explanation}")
        out += [f"  - {_cite(d.record)}", f"  - {_cite(d.cctv)}"]
    for s in inv.speculation:
        if s.about:
            out.append(f"- **Speculation** by {s.speaker} about {', '.join(s.about)} (weighs 0): {_cite(s.quote)}")
    for m in inv.motives:
        if m.person != top.suspect and m.person in a.logs:
            out.append(f"- **Motive for {m.person}**, outweighed by the rest of the evidence: {m.describe()} "
                       f"{_cite(m.quote)}")
    assumptions = [s for s in top.steps if s.label is Label.ASSUMPTION and s.weight != 0]
    if assumptions:
        out += ["", f"Assumptions in the case against {top.suspect} (each could be wrong):"]
        for s in assumptions:
            out += _step_lines(s)
    out.append("")

    if inv.window:
        w = inv.window
        disputed = {d.record for d in inv.disputes}
        out += ["## Records during the crime window", "",
                f"Window {w.start:%Y-%m-%d %H:%M} to {w.end:%Y-%m-%d %H:%M} at {w.scene}, opened by "
                f"{_cite(w.start_quote)} and closed by {_cite(w.end_quote)}.", ""]
        for e in inv.timeline.records():
            if w.start <= e.time <= w.end and case.documents[e.doc_id].type != "brief":
                flag = " *(disputed)*" if e.quote in disputed else ""
                out.append(f"- {e.time:%m-%d %H:%M}{flag}: {_cite(e.quote)}")
        out.append("")

    if earlier is not None:
        out += _reassessment(inv, earlier)

    if a.rejections:
        out += ["## LLM steps rejected", ""]
        out += [f"- {r.reason}: {r.item.get('reasoning', '')}" for r in a.rejections]
        out.append("")

    body = "\n".join(out)
    check = check_citations(case, body)
    if not check.ok:
        raise ReportCitationError("; ".join(check.problems))
    body += ("\n## Citation check\n\n"
             f"All {check.quoted} quoted citations and {check.references} line references in this report were "
             f"checked against the source documents: every one matches.\n")
    return body


def _reassessment(inv, earlier) -> list[str]:
    case: Case = inv.index.case
    old, new = earlier.assessment, inv.assessment
    added = [d for d in case.documents.values() if d.id not in earlier.index.case.documents]
    out = ["## How the conclusion changed as evidence arrived", "",
           f"With the first {len(earlier.index.case.documents)} documents, the most likely suspect was "
           f"**{old.most_likely}** ({old.logs[old.most_likely].score:+.1f}, confidence {old.confidence()[0]}). "
           f"New evidence:", ""]
    for d in added:
        kind = "record" if d.kind is EvidenceKind.RECORD else "statement"
        out.append(f"- `{d.id}` ({kind}, stage {d.stage}): {d.title}")
    out += ["", f"Now the most likely suspect is **{new.most_likely}** "
            f"({new.logs[new.most_likely].score:+.1f}, confidence {new.confidence()[0]}).", "",
            "| Suspect | Before | After | Change |", "|---|---|---|---|"]
    for name in new.logs:
        b, n = old.logs[name].score, new.logs[name].score
        out.append(f"| {name} | {b:+.1f} | {n:+.1f} | {n - b:+.1f} |")
    out.append("")
    for name in dict.fromkeys([old.most_likely, new.most_likely]):
        before = {s.text for s in old.logs[name].steps}
        after = {s.text for s in new.logs[name].steps}
        gone = [s for s in old.logs[name].steps if s.text not in after and s.weight != 0]
        came = [s for s in new.logs[name].steps if s.text not in before and s.weight != 0]
        if gone or came:
            out += [f"What changed for {name}:", ""]
            for s in gone:
                out.append(f"- no longer counted ({s.weight:+.1f}): {s.text}")
            for s in came:
                out.append(f"- new ({s.weight:+.1f}): {s.text}")
            out.append("")
    return out
